POSTER_METRICS = ["bleu", "chrf", "comet", "metricx", "cometkiwi23"]


def stat_value(key: str) -> float:
    with open("results/paper_stats.json") as source:
        return json.load(source)[key]["value"]


def _latex_decimal(value: float) -> str:
    """Format a three-decimal correlation in the poster's house style."""
    rendered = f"{value:.3f}"
    if rendered.startswith("0."):
        return rendered[1:]
    if rendered.startswith("-0."):
        return "-" + rendered[2:]
    return rendered


def generate_poster_stats() -> None:
    """Generate poster-only TeX macros directly from audited result files."""
    en_zh = pd.read_csv("results/en_zh_correlations.csv")
    pooled = en_zh.loc[en_zh["year"] == "pooled", "comet"]
    if len(pooled) != 1:
        raise ValueError("Expected one pooled COMET row in en_zh_correlations.csv")
    value = _latex_decimal(float(pooled.iloc[0]))
    Path("poster/poster_stats_generated.tex").write_text(
        "% Auto-generated by poster/make_poster_plots.py. Do not edit.\n"
        "% Source: results/en_zh_correlations.csv\n"
        f"\\newcommand{{\\EnZhCOMETRho}}{{{value}}}\n",
        encoding="utf-8",
    )


def pipeline_diagram() -> None:
    """Three-tier overview with no arrows and large poster-scale labels."""
    fig, ax = plt.subplots(figsize=(7.2, 2.55))
    ax.set_xlim(0, 7.2)
    ax.set_ylim(0, 2.55)
    ax.axis("off")

    tiers = [
        ("Tier 1a: Human MQM", 1.2, BYU_NAVY,
         "Professional span-level MQM", "de, es, he, ru, zh"),
        ("Tier 1b: Human DA", 3.6, BYU_GREEN,
         "Human sentence-level\nDA scores",
         "bn, cs, et, fi, fr, gu, ha,\nhi, is, ja, kk, km, lt, lv,\npl, ps, ta, tr, uk, xh, zu"),
        ("Tier 2: Synthetic MQM", 6.0, BYU_PLUM,
         "NLLB hypotheses +\nLlama MQM", "am, ht, ka, lo, my, sw, th"),
    ]
    for label, x, color, explanation, languages in tiers:
        ax.add_patch(mpatches.FancyBboxPatch(
            (x - 1.05, 0.85), 2.10, 1.15,
            boxstyle="round,pad=0.10", linewidth=2,
            edgecolor=color, facecolor="white",
        ))
        ax.text(x, 1.70, label, ha="center", va="center",
                fontsize=11.2, fontweight="bold", color=color)
        ax.text(x, 1.44, explanation, ha="center", va="center",
                fontsize=8.8, fontweight="bold", color=BYU_NAVY,
                linespacing=1.0)
        language_size = 8.4 if x == 3.6 else 9.8
        language_y = 1.08 if x in (3.6, 6.0) else 1.16
        ax.text(x, language_y, languages, ha="center", va="center",
                fontsize=language_size, color=BYU_NAVY, linespacing=1.15)

    ax.text(
        3.6, 0.45,
        "10 metrics  |  Spearman $\\rho$ against quality judgments",
        ha="center", va="center", fontsize=10.5, color="white",
        bbox=dict(boxstyle="round,pad=0.35", facecolor=BYU_ROYAL,
                  edgecolor=BYU_ROYAL),
    )
    ax.set_title("Three Annotation Tiers Across 33 Languages", fontsize=13, pad=4,
                 color=BYU_NAVY, fontweight="bold")
    plt.tight_layout(pad=0.15)
    fig.savefig(OUT / "pipeline_poster.pdf", bbox_inches="tight")
    plt.close(fig)


def direction_morphology() -> None:
    morphs = ["Agglutinative", "Fusional"]
    entox = [stat_value("DirMorphCOMETEntoXAgglutin"),
             stat_value("DirMorphCOMETEntoXFusional")]
    xtoen = [stat_value("DirMorphCOMETXtoEnAgglutin"),
             stat_value("DirMorphCOMETXtoEnFusional")]
    entox_err = np.array([
        [entox[0] - stat_value("DirMorphCOMETEntoXAgglutinCIlo"),
         entox[1] - stat_value("DirMorphCOMETEntoXFusionalCIlo")],
        [stat_value("DirMorphCOMETEntoXAgglutinCIhi") - entox[0],
         stat_value("DirMorphCOMETEntoXFusionalCIhi") - entox[1]],
    ])
    xtoen_err = np.array([
        [xtoen[0] - stat_value("DirMorphCOMETXtoEnAgglutinCIlo"),
         xtoen[1] - stat_value("DirMorphCOMETXtoEnFusionalCIlo")],
        [stat_value("DirMorphCOMETXtoEnAgglutinCIhi") - xtoen[0],
         stat_value("DirMorphCOMETXtoEnFusionalCIhi") - xtoen[1]],
    ])

    fig, ax = plt.subplots(figsize=(6.2, 3.8))
    x = np.arange(2)
    width = 0.32
    first = ax.bar(x - width / 2, entox, width, yerr=entox_err, capsize=4,
                   label="en$\\to$X", color=BYU_ROYAL, zorder=3)
    second = ax.bar(x + width / 2, xtoen, width, yerr=xtoen_err, capsize=4,
                    label="X$\\to$en", color=BYU_LIGHT_BLUE, zorder=3)
    for bars, values, text_color in [(first, entox, "white"),
                                      (second, xtoen, BYU_NAVY)]:
        for bar, value in zip(bars, values):
            ax.text(bar.get_x() + bar.get_width() / 2, 0.025, f"{value:.2f}",
                    ha="center", va="bottom", fontsize=11,
                    fontweight="bold", color=text_color)
    for i, gap in enumerate([stat_value("GapDirAgglutin"),
                              stat_value("GapDirFusional")]):
        ax.text(i, max(entox[i], xtoen[i]) + 0.15, f"+{gap:.3f}",
                ha="center", fontsize=11, fontweight="bold", color=BYU_SLATE)
    ax.set_xticks(x, morphs, fontsize=12)
    ax.set_ylabel("COMET Spearman $\\rho$", fontsize=12)
    ax.set_ylim(0, 1.05)
    ax.set_title("Translation Direction Matters More Than Morphology", fontsize=14,
                 color=BYU_NAVY, fontweight="bold")
    ax.legend(frameon=False, fontsize=13, loc="upper left",
              handlelength=1.5, labelspacing=0.35)
    ax.tick_params(labelsize=11)
    ax.spines[["top", "right"]].set_visible(False)
    plt.tight_layout(pad=0.3)
    fig.savefig(OUT / "direction_morphology_poster.pdf", bbox_inches="tight")
    plt.close(fig)


def tier_bar() -> None:
    metric_keys = {
        "bleu": "BLEU", "chrf": "ChrF", "bertscore": "BERTScore",
        "bleurt": "BLEURT", "comet": "COMET", "xcomet": "xCOMET",
        "metricx": "MetricX", "cometkiwi": "KiwiXXII",
        "cometkiwi23": "KiwiXXIII", "gemba": "GEMBA",
    }
    tier_keys = {"high": "High", "medium": "Med", "low": "Low"}
    metrics = list(metric_keys)
    fig, ax = plt.subplots(figsize=(8.6, 3.0))
    x = np.arange(len(metrics))
    width = 0.25
    for offset, tier in zip([-width, 0, width], TIER_ORDER):
        values = []
        for metric in metrics:
            key = f"Tier{metric_keys[metric]}{tier_keys[tier]}Rho"
            try:
                values.append(stat_value(key))
            except KeyError:
                values.append(np.nan)
        ax.bar(x + offset, values, width, label=tier.capitalize(),
               color=TIER_COLORS[tier], edgecolor="white", linewidth=0.4)
    ax.set_xticks(x, [METRIC_LABELS[m] for m in metrics], rotation=27,
                  ha="right", fontsize=9.5)
    ax.set_ylabel("Mean Spearman $\\rho$", fontsize=10.5)
    ax.set_ylim(-0.05, 0.85)
    ax.set_title("Metric Reliability by Resource Tier", fontsize=12.5,
                 color=BYU_NAVY, fontweight="bold")
    ax.legend(frameon=False, fontsize=11.5, ncol=3, loc="upper left",
              handlelength=1.5, columnspacing=1.2)
    ax.tick_params(axis="y", labelsize=9.5)
    ax.grid(axis="y", color=BYU_LIGHT_GRAY, linewidth=0.6)
    ax.spines[["top", "right"]].set_visible(False)
    plt.tight_layout(pad=0.25)
    fig.savefig(OUT / "tier_bar_poster.pdf", bbox_inches="tight")
    plt.close(fig)


def language_heatmap(df: pd.DataFrame) -> None:
    metrics = [m for m in POSTER_METRICS if m in df["metric"].unique()]
    poster_metric_labels = {
        "bleu": "BLEU*",
        "chrf": "ChrF++",
        "comet": "COMET",
        "metricx": "MetricX-24",
        "cometkiwi23": "COMET-\nKiwi-23",
    }
    pivot = df.pivot_table(
        index="lang", columns="metric", values="spearman_r", aggfunc="mean"
    )[metrics]

    # The pipeline's default BLEU tokenizer does not segment Japanese.  Use the
    # audited FLORES-200 SentencePiece BLEU correlation for the displayed
    # en->ja row so the poster does not turn a tokenizer artifact into a
    # language-level finding.  Keep the underlying benchmark results unchanged.
    ja_audit_path = Path("results/audit_bleu_tokenization_ja.csv")
    if ja_audit_path.exists() and "ja" in pivot.index and "bleu" in pivot.columns:
        ja_audit = pd.read_csv(ja_audit_path)
        ja_spbleu = ja_audit.loc[ja_audit["metric"] == "bleu_spm", "rho"]
        if not ja_spbleu.empty:
            pivot.loc["ja", "bleu"] = float(ja_spbleu.iloc[0])

    meta = df[["lang", "resource_tier"]].drop_duplicates().set_index("lang")
    rank = {"high": 0, "medium": 1, "low": 2}
    pivot["_tier"] = pivot.index.map(
        lambda lang: rank.get(meta.loc[lang, "resource_tier"], 2)
    )
    pivot = pivot.sort_values(["_tier", metrics[-1]], ascending=[True, False])
    pivot = pivot.drop(columns="_tier")

    # Same aspect ratio as the paper figure, but a narrower source canvas.
    # LaTeX therefore enlarges fonts much more at the same poster footprint.
    fig, ax = plt.subplots(figsize=(8.0, 4.75))
    sns.heatmap(
        pivot,
        annot=True,
        fmt=".2f",
        cmap=BYU_DIVERGING,
        center=0,
        vmin=-0.2,
        vmax=0.9,
        linewidths=0.25,
        linecolor="white",
        xticklabels=[poster_metric_labels[m] for m in pivot.columns],
        yticklabels=[language.upper() for language in pivot.index],
        cbar_kws={"label": "Spearman $\\rho$", "shrink": 0.72, "pad": 0.02},
        annot_kws={"size": 9.5, "fontweight": "bold"},
        ax=ax,
    )
    ax.set_title("Five Representative Metrics by Language", fontsize=15, pad=5,
                 color=BYU_NAVY, fontweight="bold")
    ax.set_xlabel("")
    ax.set_ylabel("")
    ax.tick_params(axis="x", labelsize=11.2, rotation=0, pad=4)
    ax.tick_params(axis="y", labelsize=8.5, rotation=0, pad=2)
    for label in ax.get_xticklabels():
        label.set_ha("center")
    for label in ax.get_yticklabels():
        label.set_ha("right")

    languages = list(pivot.index)
    previous = meta.loc[languages[0], "resource_tier"]
    for i, language in enumerate(languages[1:], 1):
        tier = meta.loc[language, "resource_tier"]
        if tier != previous:
            ax.axhline(i, color="black", linewidth=1.1)
            previous = tier
    cbar = ax.collections[0].colorbar
    cbar.ax.tick_params(labelsize=11)
    cbar.ax.yaxis.label.set_size(12)
    plt.tight_layout(pad=0.25)
    fig.savefig(OUT / "language_heatmap_poster.pdf", bbox_inches="tight")
    plt.close(fig)


def kiwi_scatter(df: pd.DataFrame) -> None:
    comet = df[df["metric"] == "comet"][[
        "lang", "resource_tier", "spearman_r"
    ]].rename(columns={"spearman_r": "comet_r"})
    kiwi = df[df["metric"] == "cometkiwi23"][[
        "lang", "spearman_r"
    ]].rename(columns={"spearman_r": "kiwi23_r"})
    merged = comet.merge(kiwi, on="lang").dropna()

    fig, ax = plt.subplots(figsize=(5.8, 2.80))
    texts = []
    for tier in TIER_ORDER:
        subset = merged[merged["resource_tier"] == tier]
        if subset.empty:
            continue
        ax.scatter(
            subset["comet_r"], subset["kiwi23_r"],
            label=tier.capitalize(), color=TIER_COLORS[tier],
            s=52, alpha=0.9, zorder=3,
        )
        for _, row in subset.iterrows():
            texts.append(ax.text(
                row["comet_r"], row["kiwi23_r"], row["lang"].upper(),
                fontsize=10.5, fontweight="bold", color=TIER_COLORS[tier],
            ))

    values = pd.concat([merged["comet_r"], merged["kiwi23_r"]])
    lo, hi = values.min() - 0.04, values.max() + 0.04
    ax.plot([lo, hi], [lo, hi], "k--", lw=0.8, alpha=0.45,
            label="Equal performance")
    adjust_text(
        texts,
        ax=ax,
        arrowprops=dict(arrowstyle="-", color=BYU_SLATE, lw=0.55),
        expand=(1.2, 1.3),
        force_text=(0.25, 0.4),
        min_arrow_len=2,
    )
    ax.set(xlim=(lo, hi), ylim=(lo, hi))
    ax.set_xlabel("COMET (reference-based) Spearman $\\rho$", fontsize=11)
    ax.set_ylabel("COMET-Kiwi-23 (reference-free) Spearman $\\rho$", fontsize=11)
    ax.set_title("Reference-free COMET-Kiwi-23 vs. Reference-based COMET", fontsize=12.5,
                 color=BYU_NAVY, fontweight="bold")
    ax.legend(frameon=False, fontsize=11.5, loc="upper left",
              handlelength=1.4, labelspacing=0.3)
    ax.tick_params(labelsize=10)
    plt.tight_layout(pad=0.35)
    fig.savefig(OUT / "kiwi23_vs_comet_poster.pdf", bbox_inches="tight")
    plt.close(fig)


