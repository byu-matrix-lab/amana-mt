"""Generate the appendix language-reference table (code, name, family, script,
morphology, resource tier, annotation tier) from the canonical dicts in
mqmbench.analysis.correlation and correlations.csv, so it can never drift
from the classification actually used by the analysis (the same failure
mode fixed for Hausa's morphology label elsewhere in this pipeline).

Run from the project root:
    python3 scripts/generate_language_table.py

Writes latex/language_table_generated.tex, \input{}'d from the appendix.
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from mqmbench.analysis.correlation import (
    LANGUAGE_FAMILIES, SCRIPT_TYPES, MORPHOLOGY_TYPES, RESOURCE_TIERS, TIER2_LANGS,
)

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
LATEX = ROOT / "latex"

# Language names are a fixed structural fact (not a computed statistic), so a
# curated mapping is appropriate here -- same status as e.g. AGGLUTIN_LANGS.
LANG_NAMES = {
    "am": "Amharic", "bn": "Bengali", "cs": "Czech", "de": "German",
    "es": "Spanish", "et": "Estonian", "fi": "Finnish", "fr": "French",
    "gu": "Gujarati", "ha": "Hausa", "he": "Hebrew", "hi": "Hindi",
    "ht": "Haitian Creole", "is": "Icelandic", "ja": "Japanese",
    "ka": "Georgian", "kk": "Kazakh", "km": "Khmer", "lo": "Lao",
    "lt": "Lithuanian", "lv": "Latvian", "my": "Burmese", "pl": "Polish",
    "ps": "Pashto", "ru": "Russian", "sw": "Swahili", "ta": "Tamil",
    "th": "Thai", "tr": "Turkish", "uk": "Ukrainian", "xh": "Xhosa",
    "zh": "Chinese", "zu": "Zulu",
}

FAMILY_LABELS = {
    "indo_european": "Indo-European", "afro_asiatic": "Afro-Asiatic",
    "sino_tibetan": "Sino-Tibetan", "turkic": "Turkic",
    "austroasiatic": "Austroasiatic", "tai_kadai": "Tai-Kadai",
    "niger_congo": "Niger-Congo", "creole": "Creole",
    "dravidian": "Dravidian", "japonic": "Japonic",
    "uralic": "Uralic", "kartvelian": "Kartvelian",
}
SCRIPT_LABELS = {
    "logographic": "Logographic", "alphabetic": "Alphabetic",
    "abjad": "Abjad", "abugida": "Abugida",
}
MORPH_LABELS = {
    "isolating": "Isolating", "agglutinative": "Agglutinative", "fusional": "Fusional",
}
ANNOT_LABELS = {
    "human_mqm": "MQM", "human_da": "DA", "synthetic_mqm": "Synthetic MQM",
}


def main():
    corr = pd.read_csv(RESULTS / "correlations.csv")
    langs = sorted(corr["lang"].unique())

    lang_to_family = {l: f for f, ls in LANGUAGE_FAMILIES.items() for l in ls}
    lang_to_script = {l: s for s, ls in SCRIPT_TYPES.items() for l in ls}
    lang_to_morph = {l: m for m, ls in MORPHOLOGY_TYPES.items() for l in ls}
    lang_to_resource = {l: r for r, ls in RESOURCE_TIERS.items() for l in ls}
    lang_to_annot = corr.groupby("lang")["annotation_tier"].first().to_dict()

    rows = []
    for lang in langs:
        rows.append((
            lang,
            LANG_NAMES[lang],
            FAMILY_LABELS[lang_to_family[lang]],
            SCRIPT_LABELS[lang_to_script[lang]],
            MORPH_LABELS[lang_to_morph[lang]],
            lang_to_resource[lang].capitalize(),
            ANNOT_LABELS[lang_to_annot[lang]],
        ))

    lines = [
        "% AUTO-GENERATED by scripts/generate_language_table.py -- DO NOT EDIT BY HAND",
        r"\begin{table*}[t]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{llllllc}",
        r"\toprule",
        r"\textbf{Code} & \textbf{Language} & \textbf{Family} & \textbf{Script} & "
        r"\textbf{Morphology} & \textbf{Resource} & \textbf{Annotation} \\",
        r"\midrule",
    ]
    for code, name, family, script, morph, resource, annot in rows:
        tier2_mark = r"$^{\dagger}$" if code in TIER2_LANGS else ""
        lines.append(f"{code} & {name}{tier2_mark} & {family} & {script} & {morph} & {resource} & {annot} \\\\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\caption{All " + str(len(rows)) + r" languages in the benchmark, with language family "
        r"(\S\ref{sec:dir_morph}), script type, morphological type, resource tier, and annotation "
        r"protocol (MQM = professional Multidimensional Quality Metrics; DA = crowd-sourced Direct "
        r"Assessment; Synthetic MQM = Tier~2, unvalidated). $^{\dagger}$Tier~2 languages have no human "
        r"MT annotations (\S\ref{sec:tier2}).}",
        r"\label{tab:languages}",
        r"\end{table*}",
    ]

    out_path = LATEX / "language_table_generated.tex"
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(rows)} languages -> {out_path}")


if __name__ == "__main__":
    main()
