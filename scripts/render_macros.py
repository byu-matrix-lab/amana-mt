"""Render every macro in results/paper_stats.json to a single LaTeX file.

This is the ONLY script that writes latex/macros_generated.tex.
generate_paper_stats.py writes ONLY into results/paper_stats.json (a full
overwrite each run, not a merge — see that script's docstring for why);
this script reads that JSON exclusively and renders it. That split means
the JSON is unambiguously the single source of truth, and the .tex file is
a pure, disposable build artifact — delete it and rerunning this script
reproduces it byte-for-byte from the JSON.

Full pipeline, in order:
    python scripts/generate_paper_stats.py              # computes everything, writes JSON
    python scripts/render_macros.py                      # <- writes the .tex
    python scripts/assert_paper_invariants.py             # must pass before compiling
    python scripts/check_bibliography.py                  # whenever citations change

main.tex has a single `\input{macros_generated}` — no other macro file.

Run from project root:
    python scripts/render_macros.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
OUT_PATH = ROOT / "latex" / "macros_generated.tex"


def main():
    json_path = RESULTS / "paper_stats.json"
    if not json_path.exists():
        raise SystemExit(f"{json_path} not found — run generate_macros.py first.")

    with open(json_path) as f:
        stats = json.load(f)

    lines = [
        "% AUTO-GENERATED by scripts/render_macros.py — DO NOT EDIT BY HAND",
        "% Single source of truth: results/paper_stats.json",
        "% To change a value: fix the analysis script that produced it, rerun the",
        "% full pipeline (see this script's docstring), then rerun render_macros.py.",
        "%",
    ]
    for key in sorted(stats.keys()):
        fmt_value = stats[key]["fmt"]
        source = stats[key].get("source", "")
        lines.append(rf"\newcommand{{\{key}}}{{{fmt_value}}}  % {source}")
    lines.append("")

    with open(OUT_PATH, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Rendered {len(stats)} macros → {OUT_PATH}")


if __name__ == "__main__":
    main()
